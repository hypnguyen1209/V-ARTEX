"use client";

import * as React from "react";

import Link from "next/link";

import { ArrowUpCircleIcon } from "lucide-react";

import { api } from "@/lib/api";

/**
 * Top-bar update indicator: check once on page load and show available updates beside the version.
 * Clicking opens the "Version and updates" card in system settings.
 *
 * The backend caches GitHub responses for 30 minutes, so checking on every mount is safe.
 * Unauthenticated GitHub API requests are limited to 60 per hour per IP; without caching,
 * a few open tabs could exhaust the quota and prevent checks when an update is actually needed.
 *
 * Keep failures silent here; users can see the cause by selecting "Check for updates" in settings.
 */
export function UpdateBadge() {
  const [latest, setLatest] = React.useState("");

  React.useEffect(() => {
    let alive = true;
    api
      .checkUpdate()
      .then((r) => {
        // has_update already checks whether versions are comparable, so development builds show no indicator.
        if (alive && r.has_update && r.latest) setLatest(r.latest.replace(/^v(?=\d)/, ""));
      })
      .catch(() => {
        // Keep network failures and GitHub rate limits silent in the top bar.
      });
    return () => {
      alive = false;
    };
  }, []);

  if (!latest) return null;

  return (
    <Link
      href="/system/settings"
      title={`Version ${latest} is available. Click to update.`}
      className="inline-flex items-center gap-1.5 rounded-full bg-primary px-2.5 py-1 font-medium text-primary-foreground text-xs transition-opacity hover:opacity-90"
    >
      {/* A pulsing dot makes the update stand out in the busy top bar. */}
      <span className="relative flex size-1.5">
        <span className="absolute inline-flex size-full animate-ping rounded-full bg-primary-foreground opacity-75" />
        <span className="relative inline-flex size-1.5 rounded-full bg-primary-foreground" />
      </span>
      <ArrowUpCircleIcon className="size-3.5" />
      <span className="hidden sm:inline">New version {latest}</span>
      <span className="sm:hidden">New version</span>
    </Link>
  );
}
