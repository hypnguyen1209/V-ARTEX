// ---- LLM retry policy ----
// Two controls per retry layer. Both use 0 for unspecified:
//   attempts    0=default attempts | -1=disable this layer | >0=retry count
//   interval_ms 0=default exponential backoff | >0=fixed interval in milliseconds
export interface LLMRetryRule {
  attempts: number;
  interval_ms: number;
}

// Three endpoint-specific retry layers that a profile can override.
export interface LLMRetryOverride {
  connect: LLMRetryRule; // Connection retries: resets/timeouts/429/5xx before streaming begins.
  empty: LLMRetryRule; // Empty-response retries: completion without any content (openai format only).
  stream: LLMRetryRule; // Same-provider safe-window retries: replay a broken stream before any output is delivered.
}

// Global policy: defaults for the three layers above plus two global-only layers:
//   breaker: pool circuit breaker (attempts=consecutive transient failures; interval_ms=fixed cooldown)
//   intent: rerun the entire intent after a worker ends with model_error
export interface LLMRetryPolicy extends LLMRetryOverride {
  breaker: LLMRetryRule;
  intent: LLMRetryRule;
}

