-- =====================================================================
-- 0. Shared: updated_at trigger
-- =====================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

-- Safe text-to-inet conversion: invalid values yield NULL instead of error 22P02. assets.ip is free text
-- (agents / the asset API may write hostnames); a bare a.ip::inet cast lets one bad row break the entire
-- company-assignment recalculation. Callers use try_inet(...) IS NULL to identify and warn about these rows.
-- Avoid pg_input_is_valid because it requires PG16+; existing older databases must remain supported.
CREATE OR REPLACE FUNCTION try_inet(value text) RETURNS inet AS $$
BEGIN
    RETURN value::inet;
EXCEPTION WHEN others THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE STRICT;

