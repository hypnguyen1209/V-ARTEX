-- =====================================================================
-- M. Finding IM notifications
--
-- Three separate tables contain failure impact: the finding transaction (RecordFindingTx, holding
-- a task row lock) performs one blind INSERT, without reading channels or evaluating user filters.
-- Otherwise a misconfigured webhook filter could abort the transaction and lose the finding.
--
-- notification_channels: mutable channel configuration, including credentials, managed in UI.
-- notification_events: event facts, inserted in the finding transaction with a rendering snapshot.
-- notification_deliveries: delivery jobs from fan-out outside that transaction; state/retries/batches.
-- =====================================================================

-- Any number of channels per kind (e.g. separate DingTalk bots for emergency and routine groups).
-- Server validates kind against an allowlist; no CHECK, as with findings.status.
-- Adding channel kinds should not require schema changes.
CREATE TABLE IF NOT EXISTS notification_channels (
    id           BIGSERIAL PRIMARY KEY,
    name         TEXT NOT NULL,
    -- dingtalk DingTalk / feishu Feishu / wecom WeCom / webhook generic / telegram / email.
    kind         TEXT NOT NULL,
    enabled      BOOLEAN NOT NULL DEFAULT true,
    -- Credentials stored in plaintext, masked by UI (server maskChannelSecrets). Channel fields differ,
    -- so use JSONB with strict per-kind validation in Go instead of many nullable columns:
    --   dingtalk {webhook,secret}
    --   feishu   {webhook,secret}
    --   wecom    {webhook}
    --   webhook  {url,method,content_type,headers{},body_template}
    --   telegram {bot_token,chat_id,base_url}
    --   email    {host,port,username,password,from,to[],tls}
    config       JSONB NOT NULL DEFAULT '{}',
    -- Delivery mode: realtime on match / digest groups events into one message on the global interval.
    mode         TEXT NOT NULL DEFAULT 'realtime',
    -- Optional filter fields (omitted means no filter):
    --   min_severity       ''|low|medium|high|critical
    -- task_ids/asset_ids: empty arrays allow all; otherwise require nonempty intersection.
    -- vulnclass_include/exclude: case-insensitive substring keywords; empty include allows all.
    -- on_status_change: bool, meaningful only for realtime mode.
    filter       JSONB NOT NULL DEFAULT '{}',
    -- Deliveries per minute; 0=unlimited. Default 20 matches DingTalk/WeCom hard limits.
    -- Rate-limited messages are deferred to the next tick, not discarded.
    rate_per_min INTEGER NOT NULL DEFAULT 20,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
DROP TRIGGER IF EXISTS trg_notification_channels_upd ON notification_channels;
CREATE TRIGGER trg_notification_channels_upd BEFORE UPDATE ON notification_channels
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Event facts are written in the same transaction as RecordFindingTx / status changes, atomically
-- recording both the finding and notification event, without a commit-before-enqueue loss window.
-- The redundant snapshot preserves event-time names/severity/status even after edits and avoids
-- querying findings/tasks/assets again during fan-out and rendering.
-- Events survive finding deletion, as findings survive task deletion.
CREATE TABLE IF NOT EXISTS notification_events (
    id         BIGSERIAL PRIMARY KEY,
    -- finding_created | finding_status_changed
    kind       TEXT NOT NULL,
    finding_id BIGINT NOT NULL,
    snapshot   JSONB NOT NULL,
    -- Idempotent fan-out marker: dispatcher selects pending events by this column and then sets true.
    -- Retain the row so delivery history can trace back to its event.
    fanned_out BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notification_events_pending
    ON notification_events(id) WHERE NOT fanned_out;

-- One delivery row per event x enabled channel. Fan-out happens outside the finding transaction;
-- enabling a channel later does not replay history (as with agent_triggers),
-- preventing a flood of old events on activation.
-- channel_id cascades on deletion: history is meaningless once channel configuration is gone.
CREATE TABLE IF NOT EXISTS notification_deliveries (
    id          BIGSERIAL PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES notification_events(id) ON DELETE CASCADE,
    channel_id  BIGINT NOT NULL REFERENCES notification_channels(id) ON DELETE CASCADE,
    -- pending / sent / failed (retries exhausted, manual retry allowed) / skipped (disabled or canceled).
    -- pending / sending (claimed with an active lease) / sent /
    -- failed (exhausted retries or permanent failure, manual retry allowed) / skipped (disabled channel).
    -- No CHECK; server validates against an allowlist, as with findings.status.
    state       TEXT NOT NULL DEFAULT 'pending',
    attempts    INTEGER NOT NULL DEFAULT 0,
    -- next_attempt_at is both the next claim time and lease deadline: move it forward when claiming.
    -- The same predicate handles active leases and retry delays, without a separate
    -- lease_until column. A crashed process's sending rows become claimable when leases expire.
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error  TEXT NOT NULL DEFAULT '',
    -- Shared within a digest batch; always NULL for realtime. Render the batch once and mark all sent.
    batch_id    BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at     TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_due
    ON notification_deliveries(next_attempt_at) WHERE state='pending';
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_history
    ON notification_deliveries(id DESC);
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_batch
    ON notification_deliveries(batch_id) WHERE batch_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notification_deliveries_channel
    ON notification_deliveries(channel_id, id DESC);
